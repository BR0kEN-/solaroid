drop trigger plant_pv_changes_validate_spending on public.plant_pv_changes;

create or replace function public.validate_plant_pv_change_spending()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.spending_id is not null and not exists (
    select 1
    from public.plant_spendings
    where id = new.spending_id
      and plant_id = new.plant_id
      and type = new.type
  ) then
    raise exception 'Linked PV spending must match the event plant and type';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(new.operations) operation
    where coalesce(operation ->> 'kind', '') not in (
      'increase_field',
      'add_field',
      'decrease_field',
      'remove_field'
    )
  ) then
    raise exception 'PV change contains an unsupported operation';
  end if;

  if new.type = 'improvement' and exists (
    select 1
    from jsonb_array_elements(new.operations) operation
    where coalesce(operation ->> 'kind', '') not in ('increase_field', 'add_field')
  ) then
    raise exception 'Improvement PV changes may only increase capacity';
  end if;

  return new;
end;
$$;

create trigger plant_pv_changes_validate_spending
before insert or update on public.plant_pv_changes
for each row
execute function public.validate_plant_pv_change_spending();

drop trigger plant_spendings_preserve_pv_change_type on public.plant_spendings;
drop function public.prevent_non_improvement_pv_change_spending();

create function public.prevent_incompatible_pv_change_spending()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if exists (
    select 1
    from public.plant_pv_changes
    where spending_id = new.id
      and (
        plant_id is distinct from new.plant_id
        or type is distinct from new.type
      )
  ) then
    raise exception 'A spending linked to PV changes must keep its plant and type';
  end if;

  return new;
end;
$$;

create trigger plant_spendings_preserve_pv_change_linkage
before update of plant_id, type on public.plant_spendings
for each row
execute function public.prevent_incompatible_pv_change_spending();
