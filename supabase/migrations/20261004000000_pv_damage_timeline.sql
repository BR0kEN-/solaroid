alter table public.plant_pv_changes
  add column id bigint generated by default as identity,
  add column plant_id text,
  add column type text;

with ordered_changes as (
  select
    spending_id,
    row_number() over (order by date, spending_id) as event_id
  from public.plant_pv_changes
)
update public.plant_pv_changes changes
set id = ordered_changes.event_id
from ordered_changes
where ordered_changes.spending_id = changes.spending_id;

select setval(
  pg_get_serial_sequence('public.plant_pv_changes', 'id'),
  coalesce(max(id), 1),
  max(id) is not null
)
from public.plant_pv_changes;

alter table public.plant_pv_changes
  alter column id set generated always;

update public.plant_pv_changes changes
set
  plant_id = spendings.plant_id,
  type = spendings.type
from public.plant_spendings spendings
where spendings.id = changes.spending_id;

alter table public.plant_pv_changes
  drop constraint plant_pv_changes_pkey,
  drop constraint plant_pv_changes_spending_id_fkey,
  alter column spending_id drop not null,
  alter column plant_id set not null,
  alter column type set not null,
